CREATE TABLE universities (
    university_id NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    university_name VARCHAR2(100) NOT NULL,
    school_email_domain VARCHAR2(100) NOT NULL UNIQUE,
    latitude NUMBER(10,7),
    longitude NUMBER(10,7),
    boundary_radius_m NUMBER(10),
    created_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT ck_universities_radius
        CHECK (boundary_radius_m IS NULL OR boundary_radius_m > 0)
);

CREATE TABLE app_users (
    user_id NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    university_id NUMBER(19) NOT NULL,
    firebase_uid VARCHAR2(128) NOT NULL UNIQUE,
    email VARCHAR2(100) NOT NULL UNIQUE,
    name VARCHAR2(50) NOT NULL,
    nickname VARCHAR2(50),
    phone VARCHAR2(20),
    is_email_verified NUMBER(1) DEFAULT 0 NOT NULL,
    account_status VARCHAR2(20) DEFAULT 'ACTIVE' NOT NULL,
    created_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    updated_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT fk_app_users_university
        FOREIGN KEY (university_id) REFERENCES universities(university_id),
    CONSTRAINT uq_app_users_user_university
        UNIQUE (user_id, university_id),
    CONSTRAINT ck_app_users_email_verified
        CHECK (is_email_verified IN (0, 1)),
    CONSTRAINT ck_app_users_account_status
        CHECK (account_status IN ('ACTIVE', 'SUSPENDED', 'WITHDRAWN'))
);

CREATE OR REPLACE TRIGGER trg_users_set_updated_at
BEFORE INSERT OR UPDATE ON app_users
FOR EACH ROW
BEGIN
    :NEW.email := LOWER(TRIM(:NEW.email));
    IF INSERTING THEN
        :NEW.created_at := NVL(:NEW.created_at, SYSTIMESTAMP);
    END IF;
    :NEW.updated_at := SYSTIMESTAMP;
END;
/

CREATE TABLE email_verifications (
    verification_id NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id NUMBER(19) NOT NULL,
    email VARCHAR2(100) NOT NULL,
    verification_code VARCHAR2(20) NOT NULL,
    purpose VARCHAR2(30) NOT NULL,
    is_verified NUMBER(1) DEFAULT 0 NOT NULL,
    expires_at TIMESTAMP NOT NULL,
    verified_at TIMESTAMP,
    created_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT fk_email_verifications_user
        FOREIGN KEY (user_id) REFERENCES app_users(user_id),
    CONSTRAINT ck_email_verifications_verified
        CHECK (is_verified IN (0, 1)),
    CONSTRAINT ck_email_verifications_purpose
        CHECK (purpose IN ('SIGN_UP', 'SCHOOL_EMAIL', 'PASSWORD_RESET')),
    CONSTRAINT ck_email_verifications_email
        CHECK (email = LOWER(TRIM(email))),
    CONSTRAINT ck_email_verifications_verified_at
        CHECK (
            (is_verified = 0 AND verified_at IS NULL) OR
            (is_verified = 1 AND verified_at IS NOT NULL)
        )
);

CREATE INDEX idx_email_verifications_user_purpose
    ON email_verifications (user_id, purpose, is_verified);

CREATE TABLE service_zones (
    zone_id NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    university_id NUMBER(19) NOT NULL,
    zone_name VARCHAR2(100) NOT NULL,
    zone_type VARCHAR2(20) NOT NULL,
    latitude NUMBER(10,7) NOT NULL,
    longitude NUMBER(10,7) NOT NULL,
    radius_m NUMBER(10) NOT NULL,
    is_active NUMBER(1) DEFAULT 1 NOT NULL,
    created_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT fk_service_zones_university
        FOREIGN KEY (university_id) REFERENCES universities(university_id),
    CONSTRAINT uq_service_zones_name
        UNIQUE (university_id, zone_name),
    CONSTRAINT uq_service_zones_zone_university
        UNIQUE (zone_id, university_id),
    CONSTRAINT ck_service_zones_type
        CHECK (zone_type IN ('SCHOOL', 'STATION', 'CUSTOM')),
    CONSTRAINT ck_service_zones_active
        CHECK (is_active IN (0, 1)),
    CONSTRAINT ck_service_zones_radius
        CHECK (radius_m > 0)
);

CREATE INDEX idx_service_zones_university
    ON service_zones (university_id);

CREATE TABLE match_requests (
    request_id NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id NUMBER(19) NOT NULL,
    university_id NUMBER(19) NOT NULL,
    start_zone_id NUMBER(19) NOT NULL,
    target_zone_id NUMBER(19) NOT NULL,
    direction_type VARCHAR2(20) NOT NULL,
    request_status VARCHAR2(20) DEFAULT 'WAITING' NOT NULL,
    desired_departure_at TIMESTAMP NOT NULL,
    max_wait_minutes NUMBER(3) DEFAULT 15 NOT NULL,
    requested_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    expired_at TIMESTAMP,
    cancelled_at TIMESTAMP,
    matched_at TIMESTAMP,
    active_request_flag NUMBER(1) DEFAULT 1 NOT NULL,
    CONSTRAINT fk_match_requests_user_university
        FOREIGN KEY (user_id, university_id) REFERENCES app_users(user_id, university_id),
    CONSTRAINT fk_match_requests_university
        FOREIGN KEY (university_id) REFERENCES universities(university_id),
    CONSTRAINT fk_match_requests_start_zone_university
        FOREIGN KEY (start_zone_id, university_id) REFERENCES service_zones(zone_id, university_id),
    CONSTRAINT fk_match_requests_target_zone_university
        FOREIGN KEY (target_zone_id, university_id) REFERENCES service_zones(zone_id, university_id),
    CONSTRAINT ck_match_requests_direction
        CHECK (direction_type IN ('SCHOOL_TO_STATION', 'STATION_TO_SCHOOL')),
    CONSTRAINT ck_match_requests_status
        CHECK (request_status IN ('WAITING', 'MATCHED', 'CANCELLED', 'EXPIRED')),
    CONSTRAINT ck_match_requests_active_flag
        CHECK (active_request_flag IN (0, 1)),
    CONSTRAINT ck_match_requests_wait_minutes
        CHECK (max_wait_minutes BETWEEN 1 AND 120),
    CONSTRAINT ck_match_requests_zone_diff
        CHECK (start_zone_id <> target_zone_id),
    CONSTRAINT ck_match_requests_status_timestamps
        CHECK (
            (request_status = 'WAITING' AND matched_at IS NULL AND cancelled_at IS NULL AND expired_at IS NULL) OR
            (request_status = 'MATCHED' AND matched_at IS NOT NULL) OR
            (request_status = 'CANCELLED' AND cancelled_at IS NOT NULL) OR
            (request_status = 'EXPIRED' AND expired_at IS NOT NULL)
        )
);

CREATE OR REPLACE TRIGGER trg_match_requests_set_active_flag
BEFORE INSERT OR UPDATE OF request_status, matched_at, cancelled_at, expired_at, active_request_flag
ON match_requests
FOR EACH ROW
BEGIN
    IF :NEW.request_status = 'WAITING' THEN
        :NEW.active_request_flag := 1;
    ELSE
        :NEW.active_request_flag := 0;
    END IF;
END;
/

CREATE UNIQUE INDEX uq_match_requests_waiting_user
    ON match_requests (
        CASE WHEN active_request_flag = 1 THEN user_id END
    );

CREATE INDEX idx_match_requests_matching
    ON match_requests (
        university_id,
        start_zone_id,
        target_zone_id,
        direction_type,
        request_status,
        desired_departure_at
    );

CREATE TABLE match_groups (
    match_group_id NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    university_id NUMBER(19) NOT NULL,
    start_zone_id NUMBER(19) NOT NULL,
    target_zone_id NUMBER(19) NOT NULL,
    direction_type VARCHAR2(20) NOT NULL,
    target_user_count NUMBER(2) DEFAULT 4 NOT NULL,
    matched_user_count NUMBER(2) DEFAULT 0 NOT NULL,
    match_status VARCHAR2(20) DEFAULT 'FORMING' NOT NULL,
    scheduled_departure_at TIMESTAMP NOT NULL,
    created_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    matched_at TIMESTAMP,
    cancelled_at TIMESTAMP,
    CONSTRAINT fk_match_groups_university
        FOREIGN KEY (university_id) REFERENCES universities(university_id),
    CONSTRAINT fk_match_groups_start_zone_university
        FOREIGN KEY (start_zone_id, university_id) REFERENCES service_zones(zone_id, university_id),
    CONSTRAINT fk_match_groups_target_zone_university
        FOREIGN KEY (target_zone_id, university_id) REFERENCES service_zones(zone_id, university_id),
    CONSTRAINT uq_match_groups_group_university
        UNIQUE (match_group_id, university_id),
    CONSTRAINT ck_match_groups_direction
        CHECK (direction_type IN ('SCHOOL_TO_STATION', 'STATION_TO_SCHOOL')),
    CONSTRAINT ck_match_groups_status
        CHECK (match_status IN ('FORMING', 'COMPLETED', 'CANCELLED')),
    CONSTRAINT ck_match_groups_target_count
        CHECK (target_user_count BETWEEN 2 AND 4),
    CONSTRAINT ck_match_groups_matched_count
        CHECK (matched_user_count BETWEEN 0 AND target_user_count),
    CONSTRAINT ck_match_groups_zone_diff
        CHECK (start_zone_id <> target_zone_id),
    CONSTRAINT ck_match_groups_status_timestamps
        CHECK (
            (match_status = 'FORMING' AND matched_at IS NULL AND cancelled_at IS NULL) OR
            (match_status = 'COMPLETED' AND matched_at IS NOT NULL) OR
            (match_status = 'CANCELLED' AND cancelled_at IS NOT NULL)
        )
);

CREATE INDEX idx_match_groups_lookup
    ON match_groups (
        university_id,
        start_zone_id,
        target_zone_id,
        direction_type,
        match_status,
        scheduled_departure_at
    );

CREATE TABLE match_group_members (
    match_group_member_id NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    match_group_id NUMBER(19) NOT NULL,
    university_id NUMBER(19) NOT NULL,
    user_id NUMBER(19) NOT NULL,
