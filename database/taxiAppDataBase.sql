    CONSTRAINT fk_match_group_members_user
        FOREIGN KEY (user_id, university_id) REFERENCES app_users(user_id, university_id),
    CONSTRAINT fk_match_group_members_request
        FOREIGN KEY (request_id) REFERENCES match_requests(request_id),
    CONSTRAINT uq_match_group_members_group_user
        UNIQUE (match_group_id, user_id),
    CONSTRAINT uq_match_group_members_request
        UNIQUE (request_id),
    CONSTRAINT ck_match_group_members_role
        CHECK (member_role IN ('LEADER', 'MEMBER')),
    CONSTRAINT ck_match_group_members_status
        CHECK (join_status IN ('JOINED', 'LEFT', 'REMOVED'))
