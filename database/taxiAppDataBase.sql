CREATE INDEX idx_match_group_members_group
    ON match_group_members (match_group_id);

CREATE TABLE chat_rooms (
    chat_room_id NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    match_group_id NUMBER(19) NOT NULL UNIQUE,
    university_id NUMBER(19) NOT NULL,
    room_status VARCHAR2(20) DEFAULT 'OPEN' NOT NULL,
    created_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    closed_at TIMESTAMP,
    CONSTRAINT fk_chat_rooms_group
        FOREIGN KEY (match_group_id, university_id) REFERENCES match_groups(match_group_id, university_id),
    CONSTRAINT uq_chat_rooms_room_university
        UNIQUE (chat_room_id, university_id),
    CONSTRAINT ck_chat_rooms_status
        CHECK (room_status IN ('OPEN', 'CLOSED')),
    CONSTRAINT ck_chat_rooms_status_timestamps
        CHECK (
            (room_status = 'OPEN' AND closed_at IS NULL) OR
            (room_status = 'CLOSED' AND closed_at IS NOT NULL)
        )
);

CREATE TABLE chat_messages (
    message_id NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    chat_room_id NUMBER(19) NOT NULL,
    university_id NUMBER(19) NOT NULL,
    sender_user_id NUMBER(19),
    message_type VARCHAR2(20) DEFAULT 'TEXT' NOT NULL,
    message_content VARCHAR2(2000),
    sent_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    is_deleted NUMBER(1) DEFAULT 0 NOT NULL,
    deleted_at TIMESTAMP,
    system_event_code VARCHAR2(30),
    CONSTRAINT fk_chat_messages_room
        FOREIGN KEY (chat_room_id, university_id) REFERENCES chat_rooms(chat_room_id, university_id),
    CONSTRAINT fk_chat_messages_sender
        FOREIGN KEY (sender_user_id, university_id) REFERENCES app_users(user_id, university_id),
    CONSTRAINT uq_chat_messages_message_room
        UNIQUE (message_id, chat_room_id),
    CONSTRAINT ck_chat_messages_type
        CHECK (message_type IN ('TEXT', 'IMAGE', 'SYSTEM')),
    CONSTRAINT ck_chat_messages_deleted
        CHECK (is_deleted IN (0, 1)),
    CONSTRAINT ck_chat_messages_sender
        CHECK (
            (message_type = 'SYSTEM' AND sender_user_id IS NULL) OR
            (message_type IN ('TEXT', 'IMAGE') AND sender_user_id IS NOT NULL)
        ),
    CONSTRAINT ck_chat_messages_payload
        CHECK (
            (message_type = 'SYSTEM' AND system_event_code IS NOT NULL AND message_content IS NOT NULL) OR
            (message_type IN ('TEXT', 'IMAGE') AND message_content IS NOT NULL AND system_event_code IS NULL)
        ),
    CONSTRAINT ck_chat_messages_deleted_at
        CHECK (
            (is_deleted = 0 AND deleted_at IS NULL) OR
            (is_deleted = 1 AND deleted_at IS NOT NULL)
        )
);

CREATE INDEX idx_chat_messages_room_time
    ON chat_messages (chat_room_id, sent_at);

CREATE TABLE chat_room_members (
    room_member_id NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    chat_room_id NUMBER(19) NOT NULL,
    university_id NUMBER(19) NOT NULL,
    user_id NUMBER(19) NOT NULL,
    joined_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    left_at TIMESTAMP,
    last_read_message_id NUMBER(19),
    last_read_at TIMESTAMP,
    CONSTRAINT fk_chat_room_members_room
        FOREIGN KEY (chat_room_id, university_id) REFERENCES chat_rooms(chat_room_id, university_id),
    CONSTRAINT fk_chat_room_members_user
        FOREIGN KEY (user_id, university_id) REFERENCES app_users(user_id, university_id),
    CONSTRAINT fk_chat_room_members_last_read_message
        FOREIGN KEY (last_read_message_id, chat_room_id) REFERENCES chat_messages(message_id, chat_room_id),
    CONSTRAINT uq_chat_room_members
        UNIQUE (chat_room_id, user_id),
    CONSTRAINT ck_chat_room_members_read_pair
        CHECK (
            (last_read_message_id IS NULL AND last_read_at IS NULL) OR
            (last_read_message_id IS NOT NULL AND last_read_at IS NOT NULL)
        )
);

CREATE INDEX idx_chat_room_members_room
    ON chat_room_members (chat_room_id);

CREATE INDEX idx_app_users_university
